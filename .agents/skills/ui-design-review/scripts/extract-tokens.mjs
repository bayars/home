#!/usr/bin/env node
/**
 * extract-tokens.mjs — bootstrap design-system/tokens.json from the corporate
 * design system's CSS custom properties (e.g. the tokens.css shipped in its
 * npm package). Categories are inferred from variable names, so review the
 * result before trusting it.
 *
 * Usage: node extract-tokens.mjs node_modules/@corp/ui/dist/tokens.css [more.css] > tokens.draft.json
 */
import { readFileSync } from 'node:fs';

const files = process.argv.slice(2);
if (!files.length) { console.error('Usage: node extract-tokens.mjs <tokens.css> [...] > tokens.draft.json'); process.exit(1); }

const vars = {};
for (const f of files) {
  const css = readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of css.matchAll(/(--[\w-]+)\s*:\s*([^;}]+)[;}]/g)) if (!(m[1] in vars)) vars[m[1]] = m[2].trim();
}
// Resolve var(--x) references one level at a time.
const resolve = (v, depth = 0) => (depth > 8 ? v : v.replace(/var\(\s*(--[\w-]+)\s*(?:,\s*([^)]+))?\)/g, (_, n, fb) => (vars[n] !== undefined ? resolve(vars[n], depth + 1) : fb || _)));

const out = { _note: 'Draft generated by extract-tokens.mjs — review categories, then save as design-system/tokens.json', color: {}, fontFamily: [], fontSize: {}, fontWeight: [], spacing: {}, radius: {}, unclassified: {} };
const isColor = (v) => /^(#[0-9a-f]{3,8}|rgba?\(|hsla?\(|oklch\(|oklab\(|lab\(|lch\(|color\()/i.test(v);
const isLen = (v) => /^-?[\d.]+(px|rem|em)?$/.test(v);
for (const [name, rawV] of Object.entries(vars)) {
  const v = resolve(rawV); const n = name.slice(2); const k = n.toLowerCase();
  if (isColor(v)) out.color[n] = v;
  else if (/font-?family|typeface|font-(sans|serif|mono|body|heading)/.test(k)) out.fontFamily.push(...v.split(',').slice(0, 1).map((s) => s.trim().replace(/^["']|["']$/g, '')));
  else if (/font-?weight|weight/.test(k) && /^\d{3}$/.test(v)) out.fontWeight.push(Number(v));
  else if (isLen(v) && /font-?size|text-|type-|fs-/.test(k)) out.fontSize[n] = v;
  else if (isLen(v) && /radius|rounded|corner/.test(k)) out.radius[n] = v;
  else if (isLen(v) && /spac|space|gap|inset|pad|margin|size-\d|gutter/.test(k)) out.spacing[n] = v;
  else if (isLen(v) || /shadow|z-?index|duration|easing|breakpoint|line-?height/.test(k)) out.unclassified[n] = v;
}
out.fontFamily = [...new Set(out.fontFamily)];
out.fontWeight = [...new Set(out.fontWeight)].sort((a, b) => a - b);
console.log(JSON.stringify(out, null, 2));
console.error(`Extracted ${Object.keys(out.color).length} colors, ${Object.keys(out.spacing).length} spacing, ${Object.keys(out.fontSize).length} font sizes, ${Object.keys(out.radius).length} radii, ${out.fontFamily.length} font families from ${Object.keys(vars).length} custom properties.`);
