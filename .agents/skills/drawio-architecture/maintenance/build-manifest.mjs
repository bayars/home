#!/usr/bin/env node
// Regenerates assets/drawio-manifest.json: the allowlist of draw.io files the
// skill may download, each with its SHA-256 and size.
//
// Maintainers only. Needs a local checkout of https://github.com/jgraph/drawio
// at the release tag you want to pin (see docs/MAINTENANCE.md).
//
//   node maintenance/build-manifest.mjs /path/to/drawio-checkout
//
// It reads files only; nothing is downloaded and nothing outside assets/ is written.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(process.argv[2] || "");
if (!process.argv[2]) { console.error("usage: build-manifest.mjs <drawio-checkout>"); process.exit(2); }
const base = "src/main/webapp";
// Everything the viewer can ask for while rendering a diagram.
const roots = ["js/viewer-static.min.js", "stencils", "img", "mxgraph/images", "styles"];

const walk = (abs, rel, out) => {
  const st = statSync(abs);
  if (st.isDirectory()) { for (const n of readdirSync(abs).sort()) walk(join(abs, n), rel + "/" + n, out); }
  else if (st.isFile()) out.push([rel, abs, st.size]);
  return out;
};
const files = {};
let bytes = 0;
for (const r of roots) for (const [rel, abs, size] of walk(join(repo, base, r), r, [])) {
  files[rel] = [createHash("sha256").update(readFileSync(abs)).digest("base64"), size];
  bytes += size;
}
const git = (...a) => execFileSync("git", ["-C", repo, ...a], { encoding: "utf8" }).trim();
const manifest = {
  about: "Allowlist of draw.io files this skill may download. Each entry is [sha256 (base64), size in bytes]. Generated by maintenance/build-manifest.mjs; do not edit by hand.",
  repository: "https://github.com/jgraph/drawio",
  version: readFileSync(join(repo, "VERSION"), "utf8").trim(),
  commit: git("rev-parse", "HEAD"),
  base,
  files: Object.fromEntries(Object.keys(files).sort().map(k => [k, files[k]])),
};
if (!/^[0-9a-f]{40}$/.test(manifest.commit)) throw new Error("could not read the checkout's commit");
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "assets", "drawio-manifest.json");
writeFileSync(out, JSON.stringify(manifest, null, 0).replace(/\],"/g, '],\n"').replace('"files":{', '"files":{\n') + "\n");
console.log(`draw.io ${manifest.version} @ ${manifest.commit}: ${Object.keys(files).length} files, ${(bytes / 1048576).toFixed(1)} MB -> ${out}`);
